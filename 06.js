//Números
//En JS todos los datos son tratados por igual, todos son números, sean enteros o decimales.
const numero1 = 100;
const numero2 = 200;
const numero3 = 200.20;
const numero4 = 7;
const numero5 = 6;

console.log(numero1);
console.log(numero2);

//Básicamente el uso de números es por la necesidad de hacer operaciones
//La sintáxis es la misma
console.log(numero1 + numero2);  //suma
console.log(numero2 - numero1);  //resta
console.log(numero1 * numero2);  //multiplicación
console.log(numero2 / numero2);  //división
console.log(numero4 % numero5);  //módulo

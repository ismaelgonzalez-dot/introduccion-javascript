//Objeto Math
//Los métodos más utilizados de math son:

let resultado;

resultado = Math.PI; //3.14....
console.log(resultado);

resultado = Math.round(2.5); //redondea
console.log(resultado);

resultado = Math.ceil(2.5); //redondea hacia arriba
console.log(resultado);

resultado = Math.floor(2.9); //siempre redondea hacia abajo
console.log(resultado);

resultado = Math.sqrt(144); //raíz cuadrada
console.log(resultado);

resultado = Math.abs(-200); //valor absoluto
console.log(resultado);

resultado = Math.min(3, 5, 1, 8, 2, 10); //valor mínimo de un listado
console.log(resultado);

resultado = Math.max(3, 5, 1, 8, 2, 10);
console.log(resultado);

resultado = Math.random(); //genera número aleatorio
console.log(resultado);
